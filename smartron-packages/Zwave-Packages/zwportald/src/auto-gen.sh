AC_SUBST(LIBESMTP_LIBS)\
FIND_LIBZWSCENE\
AC_SUBST(LIBZWSCENE_CFLAGS)\
AC_SUBST(LIBZWSCENE_LIBS)\
FIND_SQLITE\
AC_SUBST(SQLITE_INC)\
AC_SUBST(SQLITE_LIB)\
FIND_CJSON64\
AC_SUBST(CJSON64_INC)\
AC_SUBST(CJSON64_LIB)\
FIND_CURL\
AC_SUBST(CURL_INC)\
AC_SUBST(CURL_LIB)\
#FIND_LIBFCGI\
#AC_SUBST(LIBFCGI_INC)\
#AC_SUBST(LIBFCGI_LIB)\
' configure.ac

aclocal

touch COPYING INSTALL NEWS README AUTHORS ChangeLog
